info = {"name": "Vaibhav Sharma",
        "Phone": 123456,
        "address": "abcjdjx sjjdjs",}
print(info["name"])
print(info["address"])
print(info.get("Phone"))

# .values() print all the values of dictionary
print(info.values())

# .keys() prints all the keys of dictionary
print(info.keys())

# .items() print all the key-value pairs of dictionary
print(info.items())